/**
 * Короткая подпись креатива: «Видео 7», «Баннер 3» или своё имя.
 *
 * Ads Manager называет объявления строками вроде «Реклама публикации Страницы
 * 2026-08-07-3b0be0c73140a362c46c2496da9537b0». В отчёте такое имя занимает
 * всю строку и ничего не говорит, а в чате менеджера — тем более.
 *
 * Номер это место креатива в списке компании по дате создания. Значит одной
 * строкой из базы подпись не получить: нужен весь список в том же порядке.
 * Порядок обязан быть однозначным: синхронизация записывает креативы пачкой, у
 * трёх десятков строк одна и та же дата до микросекунды, и сортировка только
 * по ней возвращает их каждый раз по-новому — «Видео 21» назавтра оказывалось
 * другим роликом. Поэтому везде сортируем по дате и следом по id.
 * Функция намеренно живёт отдельно от слоя запросов — её зовут и кабинет, и
 * бот, а тащить в бот весь server-only слой ради одной строки незачем.
 */
export function creativeLabel(
  creative: { label?: string | null; format?: string | null },
  index: number,
): string {
  if (creative.label?.trim()) return creative.label.trim();
  return `${creative.format === 'video' ? 'Видео' : 'Баннер'} ${index}`;
}
