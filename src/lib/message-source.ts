/**
 * Источник по метке в готовом сообщении.
 *
 * У ссылки на WhatsApp нет меток, как у ссылки на сайт: человек нажимает её в
 * шапке профиля, в сторис или в канале — и в переписку приходит один и тот же
 * текст. Чтобы различать, откуда он пришёл, в готовый текст каждой ссылки
 * дописывают метку в скобках: «…толық ақпарат алғым келеді (инста сторис)».
 *
 * Метку ищем только в самом конце сообщения и только среди известных: скобки
 * люди ставят и сами, и «(мама ученика)» источником стать не должно.
 */

/** Хвост сообщения в скобках — туда метку и дописывают. */
const TAIL = /\(([^()]{2,40})\)\s*$/;

/**
 * Какие слова в метке что означают. Слева — ключ, которым источник записан у
 * лида (подписи к ключам — в lead-origin.ts), справа — слова, по которым его
 * узнаём. Пишут по-разному: «инста сторис», «stories», «сториз».
 */
const TAGS: { key: string; words: string[] }[] = [
  // Раньше шапки профиля: «(тикток био)» — это страница TikTok, а не Instagram.
  { key: 'tiktok_page', words: ['тикток', 'тик', 'tiktok', 'tik', 'тт'] },
  { key: 'ig_stories', words: ['сторис', 'сториз', 'стори', 'stories', 'story'] },
  { key: 'ig_bio', words: ['био', 'bio', 'шапка'] },
  // Раньше канала: «(телеграм канал)» — это Telegram, а не канал WhatsApp.
  { key: 'telegram', words: ['телеграм', 'telegram', 'тг'] },
  { key: 'wa_channel', words: ['канал', 'channel'] },
  { key: 'threads', words: ['тредс', 'тредз', 'threads'] },
];

/** Метка источника из текста сообщения или null, если её там нет. */
export function sourceTag(text: string | null | undefined): string | null {
  const tail = text?.match(TAIL)?.[1];
  if (!tail) return null;

  const words = tail.toLowerCase().split(/[^a-zа-яё]+/).filter(Boolean);

  return TAGS.find((tag) => tag.words.some((word) => words.includes(word)))?.key ?? null;
}
