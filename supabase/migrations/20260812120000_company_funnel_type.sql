-- =============================================================================
-- Lidera Final — 06. Тип воронки компании
--
-- Не у всех клиентов есть промежуточный шаг «пробный урок»: онлайн-школа ведёт
-- лид через пробное занятие, а товарный бизнес (например, парфюмерия) продаёт
-- сразу. Тип воронки определяет, какие разделы и метрики показывать.
--
--   trial  — Лид → Пробный → Продажа
--   direct — Лид → Обработан → Продажа
-- =============================================================================

alter table public.companies
  add column funnel_type text not null default 'trial'
    check (funnel_type in ('trial', 'direct'));

comment on column public.companies.funnel_type is
  'trial — воронка с пробным занятием; direct — прямая продажа без пробного.';
