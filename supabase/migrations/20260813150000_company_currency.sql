-- =============================================================================
-- Lidera Final — валюта компании
--
-- Рекламные кабинеты Meta и TikTok выставляют счета в своей валюте: у одного
-- клиента это тенге, у другого доллар. Показывать долларовый расход со знаком
-- тенге нельзя — цифра выглядит правдоподобной и потому вводит в заблуждение
-- сильнее, чем пустой экран.
-- =============================================================================

alter table public.companies
  add column currency text not null default 'KZT'
    check (currency in ('KZT', 'USD', 'EUR', 'RUB'));

comment on column public.companies.currency is
  'Валюта отчётов компании. Совпадает с валютой рекламного кабинета.';
