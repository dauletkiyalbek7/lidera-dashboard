-- =============================================================================
-- Lidera Final — номер WhatsApp у кампании
--
-- В кампаниях с целью «переписки» реклама ведёт на конкретный номер WhatsApp.
-- Meta отдаёт его в настройках группы объявлений (promoted_object), но в
-- отчётах по расходу этого поля нет — поэтому номер закрепляем за кампанией
-- и по нему считаем: на какой номер сколько людей написало и почём.
-- =============================================================================

alter table public.campaigns
  add column whatsapp_number text;

comment on column public.campaigns.whatsapp_number is
  'Номер WhatsApp, на который ведёт кампания. NULL — кампания не в переписки.';
