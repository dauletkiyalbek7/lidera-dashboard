-- =============================================================================
-- Lidera Final — медиа креатива
--
-- Клиент хочет не таблицу с названиями, а сам ролик: посмотреть креатив и
-- рядом увидеть, сколько он стоил и сколько людей привёл.
--
-- Ссылки Meta подписаны и живут недолго, поэтому храним идентификатор видео —
-- по нему сервер каждый раз получает свежий адрес. Обложку берём в исходном
-- размере (1080×1920), а не превью 64×64, которое Meta режет по центру: на
-- таком кадре у человека обрезается лицо.
-- =============================================================================

alter table public.creatives
  add column video_id text,
  add column title    text,
  add column body     text;

comment on column public.creatives.video_id is
  'ID видео в Meta. По нему сервер получает свежую ссылку на проигрывание.';
comment on column public.creatives.title is 'Заголовок объявления.';
comment on column public.creatives.body is 'Основной текст объявления.';
