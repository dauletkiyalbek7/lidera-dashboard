-- Часовой пояс рекламного кабинета.
--
-- Meta отдаёт статистику по суткам кабинета, а не компании: у Bilimdibol
-- кабинет заведён в Asia/Omsk (+6), поэтому его день начинается в 23:00 по
-- Алматы. Пояс кабинета в Meta после создания не меняется, значит приводить
-- цифры к суткам компании приходится нам — а для этого пояс надо знать.
alter table ad_accounts add column if not exists timezone text;

comment on column ad_accounts.timezone is
  'Пояс кабинета из Meta (timezone_name). В нём приходит дневная статистика.';
