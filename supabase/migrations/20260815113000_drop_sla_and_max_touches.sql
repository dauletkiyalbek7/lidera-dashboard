-- Срок первого касания и потолок касаний убраны.
--
-- Отъём лида по невыполненному сроку отменён раньше: звонок с другого номера
-- клиент считает спамом. После этого sla_minutes ничего не решал, но в
-- настройках обещал, что лид «вернётся в очередь» — настройка, которая врёт,
-- хуже отсутствующей.
--
-- max_touches остался от напоминаний о касаниях, которых тоже больше нет:
-- его читали из базы, но нигде не использовали.
--
-- Правило теперь одно: лид уходит менеджеру на смене и остаётся у него.
alter table companies drop column if exists sla_minutes;
alter table companies drop column if exists max_touches;
