-- Валюта продаж отделена от валюты рекламных отчётов.
--
-- Это две разные вещи, и раньше они были одной. Рекламный кабинет считает в
-- долларах, и директору удобно смотреть расход именно так. Но продают в
-- Казахстане за тенге: продажник присылает в бот «260000», и это тенге, чем
-- бы ни был подписан отчёт по рекламе.
--
--   currency        — валюта рекламных отчётов: расход, цена лида, CPC;
--   sales_currency  — валюта денег компании: продажи, чеки, выручка, прибыль.
--
-- Выручка и прибыль всегда в sales_currency: пересчитывать заработанное по
-- курсу незачем, деньги пришли именно в ней.
alter table companies
  add column if not exists sales_currency text not null default 'KZT'
    check (sales_currency in ('KZT', 'USD', 'EUR', 'RUB'));

comment on column companies.currency is
  'Валюта рекламных отчётов: расход, цена лида, CPC.';
comment on column companies.sales_currency is
  'Валюта продаж и чеков: выручка, прибыль, суммы из бота.';
