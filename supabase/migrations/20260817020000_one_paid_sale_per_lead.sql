-- Одна оплаченная продажа на лид.
--
-- Продажу отмечают и в кабинете, и в боте, и оба пути ничего не знали друг о
-- друге: продажник отметил покупку на платформе, потом повторил в боте — и
-- выручка удвоилась на ровном месте. Проверкой в коде это не закрыть: путей
-- два, а гонку между ними всё равно решает база.
--
-- Отменённые и ожидающие оплаты под ограничение не попадают: их можно сколько
-- угодно, деньгами они не считаются.
create unique index sales_one_paid_per_lead
  on sales (lead_id)
  where status = 'paid' and lead_id is not null;
