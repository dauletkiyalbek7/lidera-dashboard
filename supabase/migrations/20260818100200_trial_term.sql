-- =============================================================================
-- Lidera Final — как компания называет промежуточный шаг воронки
--
-- Форма воронки у Дарына та же, что у онлайн-школы: заявка → событие, на
-- котором продают → покупка. Отличается только само событие. В школе это
-- пробный урок один на один, у Дарына — ежедневный вебинар на всех сразу.
--
-- Заводить ради этого отдельный тип воронки нельзя: правила, статусы и роли
-- у них совпадают до последнего шага, а лишний тип пришлось бы учитывать в
-- каждой проверке `funnel_type = 'trial'`. Поэтому термин отделён от
-- поведения: воронка остаётся trial, меняется только слово в интерфейсе.
--
-- Это перечисление, а не свободный текст: слово склоняется по-разному в
-- заголовке раздела, в колонке таблицы и в подписи статуса, и подобрать все
-- формы на лету нельзя.
-- =============================================================================

alter table public.companies
  add column trial_term text not null default 'trial'
    check (trial_term in ('trial', 'webinar'));

comment on column public.companies.trial_term is
  'Как называется промежуточный шаг: trial — пробный урок, webinar — вебинар. На поведение воронки не влияет.';
