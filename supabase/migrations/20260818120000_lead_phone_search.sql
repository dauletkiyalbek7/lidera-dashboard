-- =============================================================================
-- Lidera Final — поиск клиента по номеру телефона
--
-- Номера приходят из разных мест и в разном виде: «+7 7141835332» с формы,
-- «+7 (705) 630-22-99» из выгрузки, «+998 94-330-6611» у клиента из Узбекистана.
-- Человек же набирает в поиске просто цифры, как помнит — и поиск по тексту
-- на таком наборе не находит ничего.
--
-- Поэтому рядом с номером храним его же одними цифрами. Колонка вычисляемая:
-- отдельного поля, которое можно забыть обновить, не появляется.
-- =============================================================================

alter table public.leads
  add column phone_digits text
    generated always as (regexp_replace(coalesce(phone, ''), '\D', '', 'g')) stored;

comment on column public.leads.phone_digits is
  'Телефон одними цифрами — по нему ищут клиента, как бы номер ни был записан.';

-- Поиск идёт по концу и середине номера («7640360»), поэтому обычный индекс
-- по значению не сработал бы — нужен триграммный.
create extension if not exists pg_trgm;

create index leads_phone_digits_trgm_idx
  on public.leads using gin (phone_digits gin_trgm_ops);

-- Клиента ищут и по имени: номера под рукой может не быть.
create index leads_name_trgm_idx
  on public.leads using gin (name gin_trgm_ops);
