-- Покупки из переписок уходят в свой набор данных.
--
-- У переписок и у сайта наборы разные: событие с рекламы в WhatsApp Meta
-- принимает только в тот, что привязан к самому аккаунту WhatsApp. Токен для
-- отправки берём тот же, что уже введён у номера: он выдан системным
-- пользователем того же бизнес-менеджера, которому принадлежит и набор.
alter table public.whatsapp_numbers
  add column if not exists dataset_id text;

comment on column public.whatsapp_numbers.dataset_id is
  'Набор данных Meta для событий из переписок (привязан к WABA).';
