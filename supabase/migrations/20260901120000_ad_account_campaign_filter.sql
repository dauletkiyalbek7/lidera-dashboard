-- Какие кампании кабинета относятся к этому проекту.
--
-- Один рекламный кабинет обслуживает несколько проектов сразу: у Дарына в
-- одном кабинете и ҰБТ, и НИШ, всего больше тысячи кампаний. Тянуть их все в
-- один проект неверно по смыслу и невозможно на практике — Meta обрывает
-- запрос такого объёма.
--
-- Слова через запятую, сравнение без учёта регистра, достаточно одного
-- совпадения в названии. Пусто — берём все кампании, как раньше.
alter table public.ad_accounts
  add column if not exists campaign_filter text;

comment on column public.ad_accounts.campaign_filter is
  'Слова в названии кампании через запятую: берём только совпадающие. Пусто — все.';
