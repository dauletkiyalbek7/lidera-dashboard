-- Один креатив может крутиться сразу в нескольких кампаниях.
--
-- Строку статистики мы складываем по «креатив + кампания + день»: у отделов
-- продаж свои кампании, и расход одного ролика надо уметь развести по ним.
-- А ограничение стояло на «креатив + день» — и синхронизация падала на
-- кабинете, где кампании-копии крутят общий ролик.
--
-- Новый ключ шире старого, поэтому существующие строки под него подходят.
-- NULL по-прежнему ни с чем не сталкивается: строки без креатива (демо и
-- ручные записи) ведут себя как раньше.
alter table public.ad_metrics
  drop constraint if exists ad_metrics_company_id_creative_id_date_key;

create unique index if not exists ad_metrics_creative_campaign_day_idx
  on public.ad_metrics (company_id, date, creative_id, campaign_id);
