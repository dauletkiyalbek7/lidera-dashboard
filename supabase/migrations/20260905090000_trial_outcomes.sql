-- -----------------------------------------------------------------------------
-- Свои статусы для продажника.
--
-- До сих пор у урока было четыре исхода, и решение клиента приходилось
-- втискивать в них. Хуже всего ложился отказ банка: курс берут в рассрочку, и
-- «банк не одобрил» — это не отказ клиента. Человек хотел купить, продажник
-- отработал, а сделка не состоялась по причине, на которую он не влияет.
-- Считать это его провалом нельзя — иначе отчёт наказывает за чужое решение.
--
-- Добавляем два исхода:
--   thinking       — урок провели, клиент взял паузу на решение;
--   bank_declined  — хотел в рассрочку, банк отказал.
--
-- Набор менеджера при этом не меняется: он остаётся прежним, статусы
-- продажника живут отдельно и начинаются там, где менеджер передал клиента.
-- -----------------------------------------------------------------------------

alter table public.trials drop constraint if exists trials_status_check;

alter table public.trials
  add constraint trials_status_check check (
    status in (
      'scheduled',
      'completed',
      'thinking',
      'sale',
      'bank_declined',
      'rejected',
      'no_show',
      'canceled'
    )
  );

comment on column public.trials.status is
  'Исход урока глазами продажника. bank_declined — отказ банка по рассрочке: '
  'клиент хотел купить, поэтому в потери продажника это не считается.';
