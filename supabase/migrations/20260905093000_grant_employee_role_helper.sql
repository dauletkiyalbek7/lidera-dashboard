-- -----------------------------------------------------------------------------
-- Раздел «Лиды» отвечал отказом вместо списка.
--
-- Правило чтения заявок вызывает private.current_employee_role(), а право на
-- вызов у роли authenticated было отобрано вместе с public — по образцу
-- соседних помощников, у которых оно, как оказалось, никогда не отбиралось.
-- Права на функцию внутри политики Postgres проверяет от имени того, кто
-- делает запрос, поэтому любой select по заявкам падал с «permission denied
-- for function current_employee_role», а не возвращал пустой список.
--
-- Разграничение при этом не слабеет: функция security definer и возвращает
-- роль только того, кто её вызвал.
-- -----------------------------------------------------------------------------

grant execute on function private.current_employee_role() to authenticated;
