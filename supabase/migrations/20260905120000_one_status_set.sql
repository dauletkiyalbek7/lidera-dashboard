-- -----------------------------------------------------------------------------
-- Один набор статусов на кабинет и на бота.
--
-- В боте менеджер отмечает четыре исхода разговора, а в кабинете список
-- показывал восемь. Лишние два — «Дозвон» и «В работе» — нажать было негде:
-- они отвечали на вопрос «состоялся ли контакт», а менеджеру после звонка
-- надо отметить, чем разговор кончился. Списки расходились, и одна и та же
-- заявка называлась в двух местах по-разному.
--
-- Остаётся ровно то, что есть в боте: Новый, Игнор, Думает, Пробный, Купил,
-- Отказ. Существующие «Дозвон» и «В работе» переводим в «Думает» — это
-- ближайший смысл: разговор был, решение не принято.
-- -----------------------------------------------------------------------------

update public.leads
   set status = 'thinking'
 where status in ('contacted', 'in_progress');

alter table public.leads drop constraint if exists leads_status_check;

alter table public.leads
  add constraint leads_status_check check (
    status in ('new', 'no_answer', 'thinking', 'trial', 'sale', 'rejected')
  );

comment on column public.leads.status is
  'Исход разговора глазами менеджера. Набор совпадает с кнопками бота: '
  'что он нажимает в чате, то и видно в кабинете.';
