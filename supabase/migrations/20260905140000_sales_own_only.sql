-- -----------------------------------------------------------------------------
-- Продажник видит только свои чеки.
--
-- Раздел «Продажи» открывается отделу: руководителю — весь отдел, продажнику —
-- то, что закрыл он сам. Пока правило проверяло только компанию, любой
-- сотрудник читал всю выручку, и отличие держалось бы на том, что интерфейс
-- показывает не всё. Так нельзя: разделение должно стоять в базе.
--
-- Кто что видит:
--   директор (карточки сотрудника нет)  — все чеки;
--   РОП и таргетолог                    — все чеки, это их работа;
--   продажник                           — где продавец он, и чеки его клиентов;
--   менеджер                            — чеки клиентов, закреплённых за ним
--                                         (прямая воронка, где он и продаёт).
--
-- Старые чеки продавца не помнят — у них `seller_id` пуст. Для них владельца
-- определяем по заявке: иначе продажник перестал бы видеть собственную работу
-- за прошлые месяцы.
-- -----------------------------------------------------------------------------

-- Поиск «мои чеки» идёт по продавцу — без индекса это чтение всей таблицы.
create index if not exists sales_seller_idx on public.sales (company_id, seller_id);

drop policy if exists sales_select on public.sales;

create policy sales_select on public.sales
  for select to authenticated
  using (
    private.is_super_admin()
    or (
      company_id = private.current_company_id()
      and (
        private.current_employee_id() is null
        or private.current_employee_role() in ('rop', 'targetolog')
        or seller_id = private.current_employee_id()
        or private.owns_lead(lead_id)
      )
    )
  );
