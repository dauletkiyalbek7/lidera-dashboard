-- -----------------------------------------------------------------------------
-- С какого момента раздавать заявки.
--
-- У проекта, который включает раздачу не с первого дня, в базе лежит хвост
-- старых заявок. Он уходит целиком первому же человеку, открывшему смену: за
-- сегодня ему выдают двести клиентов, из которых сто семьдесят уже отработаны
-- кем-то до платформы. Мы наступили на это трижды и трижды чинили руками.
--
-- Пусто — раздаём всё, как раньше. Дата — раздаём только то, что пришло после
-- неё; старое остаётся в базе, видно в разделе «Лиды», но никому не падает.
-- -----------------------------------------------------------------------------

alter table public.companies
  add column if not exists distribute_from timestamptz;

comment on column public.companies.distribute_from is
  'Заявки старше этого момента авто-раздаче не подлежат. NULL — раздавать все.';
