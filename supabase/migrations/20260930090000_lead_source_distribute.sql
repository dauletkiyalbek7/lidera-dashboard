-- -----------------------------------------------------------------------------
-- Поток заявок без авто-раздачи.
--
-- Раздача включается на всю компанию (`companies.auto_assign`), и до сих пор
-- выбора не было: или менеджеры получают в Telegram всё, или ничего. А поток
-- заявок бывает нужен раньше людей, которые его отработают — заявки с TikTok
-- собирают историю для сквозной аналитики и CAPI, пока по ним ещё не звонят.
--
-- Выключенный поток не мешает ничему, кроме раздачи: заявки сохраняются,
-- видны в «Лидах», привязаны к креативу и кампании. Их просто никому не
-- отправляют — ни карточкой в бот, ни назначением. Директор при желании
-- назначит вручную.
--
-- По умолчанию раздаём: у действующих потоков поведение не меняется.
-- -----------------------------------------------------------------------------

alter table public.lead_sources
  add column if not exists distribute boolean not null default true;

comment on column public.lead_sources.distribute is
  'Отдавать ли заявки этого потока авто-раздаче. false — лид сохраняется, но менеджерам не уходит.';
